interface EmojiPickerProps {
  selectedEmojis: string[];
  onEmojiSelect: (emoji: string) => void;
  maxSelection?: number;
  placeholder?: string;
}

const EmojiPicker = ({ 
  selectedEmojis, 
  onEmojiSelect, 
  maxSelection = 2,
  placeholder = "Search emojis..." 
}: EmojiPickerProps) => {
  const [searchTerm, setSearchTerm] = useState('');
  const [activeCategory, setActiveCategory] = useState('Smileys & People');

  // Flatten all emojis for search
  const allEmojis = useMemo(() => {
    return Object.values(emojiData).flat();
  }, []);

  // Filter emojis based on search term
  const filteredEmojis = useMemo(() => {
    if (!searchTerm) {
      return emojiData[activeCategory] || [];
    }
    
    // Simple search - could be enhanced with emoji names/descriptions
    return allEmojis.filter(emoji => {
      // This is a basic implementation - in a real app you'd want emoji names/keywords
      return searchTerm.length <= 2; // Only show results for very short searches to avoid performance issues
    });
  }, [searchTerm, activeCategory, allEmojis]);

  const categoryNames = Object.keys(emojiData);

  return (
    <div className="w-full">
      {/* Search Input */}
      <div className="mb-4">
        <Input
          value={searchTerm}
          onChange={(e) => setSearchTerm(e.target.value)}
          placeholder={placeholder}
          className="jungle-card border-jungle-600 text-white placeholder:text-jungle-400"
        />
      </div>

      {/* Category Tabs */}
      {!searchTerm && (
        <div className="mb-4">
          <div className="flex flex-wrap gap-2">
            {categoryNames.map((category) => (
              <Button
                key={category}
                size="sm"
                variant={activeCategory === category ? "default" : "outline"}
                onClick={() => setActiveCategory(category)}
                className="text-xs"
              >
                {category}
              </Button>
            ))}
          </div>
        </div>
      )}

      {/* Emoji Grid */}
      <ScrollArea className="h-64 w-full">
        <div className="grid grid-cols-8 gap-2 p-2">
          {filteredEmojis.map((emoji, index) => {
            const isSelected = selectedEmojis.includes(emoji);
            const isDisabled = selectedEmojis.length >= maxSelection && !isSelected;

            return (
              <button
                key={`${emoji}-${index}`}
                type="button"
                onClick={() => onEmojiSelect(emoji)}
                disabled={isDisabled}
                className={`
                  w-10 h-10 text-2xl rounded-lg transition-all duration-200 relative
                  hover:scale-110 flex items-center justify-center
                  ${isSelected
                    ? 'bg-yellow-500 scale-110 shadow-lg' 
                    : 'bg-jungle-700 hover:bg-jungle-600'
                  }
                  ${isDisabled ? 'opacity-30 cursor-not-allowed' : 'cursor-pointer'}
                `}
              >
                {emoji}
                {isSelected && (
                  <span className="absolute -top-1 -right-1 w-4 h-4 bg-green-500 rounded-full text-xs flex items-center justify-center text-white">
                    ✓
                  </span>
                )}
              </button>
            );
          })}
        </div>
      </ScrollArea>

      {/* Selection Status */}
      <div className="text-xs text-jungle-400 mt-3 text-center">
        Selected: {selectedEmojis.length}/{maxSelection} emojis
        {selectedEmojis.length > 0 && (
          <div className="mt-1">
            Current selection: {selectedEmojis.join(' ')}
          </div>
        )}
      </div>
    </div>
  );
};

interface EmojiSelectorProps {
  selectedEmojis: string[];
  onEmojiChange: (emojis: string[]) => void;
  maxSelection?: number;
  label?: string;
}

const EmojiSelector = ({ 
  selectedEmojis, 
  onEmojiChange, 
  maxSelection = 2,
  label = "Pool Emoji"
}: EmojiSelectorProps) => {
  const handleEmojiSelect = (emoji: string) => {
    const current = selectedEmojis;
    if (current.includes(emoji)) {
      // Remove emoji
      onEmojiChange(current.filter(e => e !== emoji));
    } else if (current.length < maxSelection) {
      // Add emoji (max limit)
      onEmojiChange([...current, emoji]);
    }
  };

  return (
    <div>
      <div className="flex items-center justify-between mb-3">
        <span className="text-lg font-semibold text-white">
          {label} * ({maxSelection > 1 ? `1-${maxSelection} max` : '1 max'})
        </span>
        <Popover>
          <PopoverTrigger asChild>
            <Button variant="outline" size="sm">
              🎭 Browse All Emojis
            </Button>
          </PopoverTrigger>
          <PopoverContent className="w-96 jungle-card border-jungle-600" side="bottom" align="end">
            <EmojiPicker
              selectedEmojis={selectedEmojis}
              onEmojiSelect={handleEmojiSelect}
              maxSelection={maxSelection}
            />
          </PopoverContent>
        </Popover>
      </div>

      {/* Quick Selection - Popular Emojis */}
      <div className="grid grid-cols-6 gap-2 mb-3">
        {['🦁', '❤️', '🚀', '💯', '🌍', '🧧', '⚡', '🐶', '🐱', '♋', '🧳', '🎯'].map(emoji => {
          const isSelected = selectedEmojis.includes(emoji);
          const isDisabled = selectedEmojis.length >= maxSelection && !isSelected;
          
          return (
            <button
              key={emoji}
              type="button"
              onClick={() => handleEmojiSelect(emoji)}
              disabled={isDisabled}
              className={`
                w-12 h-12 text-2xl rounded-lg transition-all duration-200 relative
                ${isSelected
                  ? 'bg-yellow-500 scale-110 shadow-lg' 
                  : 'bg-jungle-700 hover:bg-jungle-600 hover:scale-105'
                }
                ${isDisabled ? 'opacity-50 cursor-not-allowed' : ''}
              `}
            >
              {emoji}
              {isSelected && (
                <span className="absolute -top-1 -right-1 w-4 h-4 bg-green-500 rounded-full text-xs flex items-center justify-center text-white">
                  ✓
                </span>
              )}
            </button>
          );
        })}
      </div>

      <div className="text-xs text-jungle-400">
        Selected: {selectedEmojis.length}/{maxSelection} emojis
        {selectedEmojis.length > 0 && (
          <span className="ml-2">Current: {selectedEmojis.join(' ')}</span>
        )}
      </div>
    </div>
  );
};

export { EmojiPicker, EmojiSelector };